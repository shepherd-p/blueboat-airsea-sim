"""Generate original procedural water assets for the public distribution.

No CAD, Fuel meshes, normal maps or skybox binaries are copied by this script.
"""
from pathlib import Path
import argparse
import struct
import sys
import numpy as np


def dds(path, faces):
    """Write uncompressed BGRA DDS, optionally with all six cubemap faces."""
    h,w=faces[0].shape[:2]
    cube=len(faces)==6
    words=[124,0x100f,h,w,w*4,0,0]+[0]*11
    words += [32,0x41,0,32,0x00ff0000,0x0000ff00,0x000000ff,0xff000000]
    words += [0x1008 if cube else 0x1000,0xfe00 if cube else 0,0,0,0]
    assert len(words)==31
    path.parent.mkdir(parents=True,exist_ok=True)
    with path.open('wb') as f:
        f.write(b'DDS '+struct.pack('<31I',*words))
        for rgba in faces:f.write(rgba[:,:,[2,1,0,3]].astype(np.uint8).tobytes())


def generate(root):
    sys.path.insert(0,str(root/'tools'))
    from generate_environment import dense_water
    base=root/'h-spar-sim/ros2_ws/src/blueboat_description/models/blueboat_water_visual'
    dense_water(base/'meshes/mesh.dae',size=120,step=10)
    n=256
    y,x=np.mgrid[:n,:n]*(2*np.pi/n)
    dx=np.zeros((n,n));dy=dx.copy()
    for kx,ky,a,phase in [(3,2,.10,.7),(7,-4,.032,1.1),(11,9,.012,2.3),(19,-13,.006,.4)]:
        c=a*np.cos(kx*x+ky*y+phase)
        dx+=kx*c;dy+=ky*c
    normal=np.stack([-dx,-dy,np.ones_like(dx)],axis=2)
    normal/=np.linalg.norm(normal,axis=2,keepdims=True)
    rgba=np.concatenate([np.clip((normal+1)*127.5,0,255).astype(np.uint8),np.full((n,n,1),255,dtype=np.uint8)],axis=2)
    dds(base/'materials/textures/wave_normals.dds',[rgba])
    sky=[]
    for face in range(6):
        t=np.linspace(0,1,64)[:,None,None]
        rgb=np.broadcast_to((1-t)*np.array([75,125,175])+t*np.array([175,200,215]),(64,64,3)).copy()
        if face==2:rgb[:]=[75,125,175]
        if face==3:rgb[:]=[25,65,85]
        sky.append(np.concatenate([rgb,np.full((64,64,1),255)],axis=2).astype(np.uint8))
    dds(base/'materials/textures/skybox_lowres.dds',sky)
    (base/'UPSTREAM.txt').write_text('Shader source: UUV Simulator Authors / Rhys Mainwaring, Apache-2.0.\nWater plane, normal texture and skybox are generated by tools/generate_public_assets.py; MIT, Fangwei and contributors. No Fuel binary assets included.\n',encoding='utf-8')
    print('Generated original water plane, normal map and skybox; no CAD required.')


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1]);a=p.parse_args();generate(a.root)
